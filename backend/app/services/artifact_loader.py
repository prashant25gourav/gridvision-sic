"""Artifact Loader Service for GridVision Backend.

Loads precomputed research and ML pipeline artifacts from data/artifacts/latest/.
Provides high-performance, in-memory caching and fast querying for FastAPI endpoints.

Operational Rules:
- Online app never re-runs clustering, forecasting, or statistics on demand.
- Strictly serves precomputed static artifacts generated by the offline pipeline.
- Resolves data/artifacts/latest with fallback to run_initial if needed.
"""

from pathlib import Path
